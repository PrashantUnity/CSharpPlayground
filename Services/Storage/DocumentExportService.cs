using System.Text;
using PdfEditorApp.Plugins.CSharpEditor.Models;
using PdfEditorApp.Plugins.CSharpEditor.Services.Kernels;
using PdfEditorApp.Plugins.CSharpEditor.Services.Languages;

namespace PdfEditorApp.Plugins.CSharpEditor.Services.Storage;

/// <summary>
/// Service responsible for exporting scripts and notebooks into standard developer formats
/// (.cs standalone files, .csx Roslyn scripts, .ipynb Jupyter notebooks, and .md Markdown documents).
/// </summary>
public static class DocumentExportService
{
    /// <summary>
    /// Exports a script into a clean standalone C# (.cs) source code file.
    /// </summary>
    public static string ExportScriptToCs(ScriptDocumentItem script)
    {
        ArgumentNullException.ThrowIfNull(script);

        var sb = new StringBuilder();
        sb.AppendLine("// ------------------------------------------------------------------------------");
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//     This code was exported from FrySharp.");
        sb.AppendLine($"//     Script: {script.Title}");
        sb.AppendLine($"//     Exported: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("// ------------------------------------------------------------------------------");
        sb.AppendLine();

        if (script.References?.Count > 0)
        {
            sb.AppendLine("// Required Package References:");
            foreach (var r in script.References)
            {
                sb.AppendLine($"//   - {r}");
            }
            sb.AppendLine();
        }

        if (!string.IsNullOrWhiteSpace(script.Notes))
        {
            sb.AppendLine("/*");
            sb.AppendLine(" * Notes & Documentation:");
            foreach (var line in script.Notes.Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None))
            {
                sb.AppendLine($" * {line}");
            }
            sb.AppendLine(" */");
            sb.AppendLine();
        }

        sb.Append(script.Code ?? string.Empty);
        if (!sb.ToString().EndsWith("\n")) sb.AppendLine();

        return sb.ToString();
    }

    /// <summary>
    /// Exports a script into a C# Script (.csx) format compatible with dotnet-script and csi.
    /// </summary>
    public static string ExportScriptToCsx(ScriptDocumentItem script)
    {
        ArgumentNullException.ThrowIfNull(script);

        var sb = new StringBuilder();
        sb.AppendLine($"// C# Script (.csx): {script.Title}");
        sb.AppendLine();

        if (script.References?.Count > 0)
        {
            foreach (var r in script.References)
            {
                if (r.StartsWith("#r", StringComparison.OrdinalIgnoreCase))
                {
                    sb.AppendLine(r);
                }
                else if (r.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                {
                    sb.AppendLine($"#r \"{r}\"");
                }
                else
                {
                    sb.AppendLine($"#r \"nuget: {r}\"");
                }
            }
            sb.AppendLine();
        }

        sb.Append(script.Code ?? string.Empty);
        if (!sb.ToString().EndsWith("\n")) sb.AppendLine();

        return sb.ToString();
    }

    /// <summary>
    /// Exports an interactive notebook into standard Jupyter Notebook (.ipynb) v4 schema format.
    /// Compatible with VS Code, JupyterLab, and GitHub notebook renderers.
    /// </summary>
    public static string ExportNotebookToIpynb(NotebookDocumentItem notebook, LanguageRegistry? languages = null) =>
        NotebookFileFormat.WriteIpynb(notebook, languages ?? StudioLanguageServices.Default.Registry);

    /// <summary>
    /// Exports an interactive notebook into clean GitHub-Flavored Markdown (.md).
    /// </summary>
    public static string ExportNotebookToMarkdown(NotebookDocumentItem notebook, LanguageRegistry? languages = null)
    {
        ArgumentNullException.ThrowIfNull(notebook);
        var registry = languages ?? StudioLanguageServices.Default.Registry;
        var defaultLanguage = DefaultLanguage(notebook, registry);

        var sb = new StringBuilder();
        sb.AppendLine($"# {notebook.Title}");
        if (!string.IsNullOrWhiteSpace(notebook.Description))
        {
            sb.AppendLine();
            sb.AppendLine(notebook.Description);
        }
        sb.AppendLine();
        sb.AppendLine($"*Exported from FrySharp • {DateTime.UtcNow:yyyy-MM-dd}*");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        int cellNum = 1;
        foreach (var cell in notebook.Cells)
        {
            if (cell.Type == CellType.Markdown)
            {
                sb.AppendLine(cell.Source ?? string.Empty);
                sb.AppendLine();
            }
            else
            {
                var countBadge = cell.ExecutionCount.HasValue ? $"[{cell.ExecutionCount.Value}]" : $"[{cellNum}]";
                var language = CellLanguage(cell, defaultLanguage, registry);
                sb.AppendLine($"### Cell {countBadge} ({language.DisplayName})");
                sb.AppendLine($"```{language.Id}");
                sb.AppendLine(cell.Source ?? string.Empty);
                sb.AppendLine("```");

                if (!string.IsNullOrWhiteSpace(cell.OutputText))
                {
                    sb.AppendLine();
                    sb.AppendLine("<details open><summary><b>Output</b></summary>");
                    sb.AppendLine();
                    sb.AppendLine("```output");
                    sb.AppendLine(cell.OutputText);
                    sb.AppendLine("```");
                    sb.AppendLine("</details>");
                    sb.AppendLine();
                }

                sb.AppendLine();
            }
            cellNum++;
        }

        return sb.ToString();
    }

    // The notebook's default language (NotebookDocumentItem.Kernel), C# when it names none the studio knows.
    private static ILanguageDefinition DefaultLanguage(NotebookDocumentItem notebook, LanguageRegistry registry) =>
        registry.Get(notebook.Kernel) ?? registry.Get(LanguageIds.CSharp) ?? registry.All.First();

    // A code cell's language: its #!python (or other) directive, its own, or the notebook's.
    private static ILanguageDefinition CellLanguage(NotebookCellItem cell, ILanguageDefinition defaultLanguage, LanguageRegistry registry)
    {
        var own = registry.Get(cell.Language) ?? defaultLanguage;
        return registry.Get(NotebookCellDirectives.LanguageOf(cell.Source, registry, own.Id)) ?? own;
    }
}
